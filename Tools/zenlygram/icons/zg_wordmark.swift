// "Zenlygram" wordmark as an Android VectorDrawable, from glyph outlines of a bundled font (CoreText).
// Run with: xcrun swift zg_wordmark.swift <font.ttf> <capHeightDp> <out.xml> [text]
//
// It replaces Telegram's "Telegram" wordmark vectors (drawable/telegram_logo_2.xml: chat-list title in DialogsActivity and
// the stories header in DialogStoriesCell; drawable/telegram_logo.xml: old intro title) under the same resource names, so
// no Java change is needed. The font is TMessagesProj/src/main/assets/fonts/rextrabold.ttf (Roboto ExtraBold, Apache-2.0,
// already shipped in the app). Fill is white: the callers tint it with a MULTIPLY colour filter.
// Telegram's wordmark has a 15.31dp cap height (telegram_logo_2) / 14.27dp (telegram_logo); pass the same value so the
// replacement sits like the original.
import CoreGraphics
import CoreText
import Foundation

let args = CommandLine.arguments
guard args.count >= 4, let capDp = Double(args[2]) else {
    FileHandle.standardError.write("usage: zg_wordmark.swift <font.ttf> <capHeightDp> <out.xml> [text]\n".data(using: .utf8)!)
    exit(2)
}
let text = args.count > 4 ? args[4] : "Zenlygram"
guard let descs = CTFontManagerCreateFontDescriptorsFromURL(URL(fileURLWithPath: args[1]) as CFURL) as? [CTFontDescriptor],
      let desc = descs.first else {
    FileHandle.standardError.write("cannot load font \(args[1])\n".data(using: .utf8)!)
    exit(1)
}
let fontSize: CGFloat = 100
let font = CTFontCreateWithFontDescriptor(desc, fontSize, nil)
let attr = NSAttributedString(string: text, attributes: [kCTFontAttributeName as NSAttributedString.Key: font,
                                                         kCTKernAttributeName as NSAttributedString.Key: 0])
let line = CTLineCreateWithAttributedString(attr)

// Collect glyph outlines in CoreText space (y up, baseline at 0).
let outline = CGMutablePath()
for run in CTLineGetGlyphRuns(line) as! [CTRun] {
    let count = CTRunGetGlyphCount(run)
    var glyphs = [CGGlyph](repeating: 0, count: count)
    var positions = [CGPoint](repeating: .zero, count: count)
    CTRunGetGlyphs(run, CFRange(location: 0, length: count), &glyphs)
    CTRunGetPositions(run, CFRange(location: 0, length: count), &positions)
    let runFont = (CTRunGetAttributes(run) as NSDictionary)[kCTFontAttributeName] as! CTFont
    for i in 0..<count {
        if let p = CTFontCreatePathForGlyph(runFont, glyphs[i], nil) {
            outline.addPath(p, transform: CGAffineTransform(translationX: positions[i].x, y: positions[i].y))
        }
    }
}
let ink = outline.boundingBoxOfPath
let pad: CGFloat = 1
// Vector space: y down, origin at the ink's top-left minus padding.
let ox = ink.minX - pad, top = ink.maxY + pad
func X(_ x: CGFloat) -> CGFloat { x - ox }
func Y(_ y: CGFloat) -> CGFloat { top - y }
func f(_ v: CGFloat) -> String {
    var s = String(format: "%.2f", Double(v))
    while s.contains(".") && (s.hasSuffix("0") || s.hasSuffix(".")) { s.removeLast() }
    return s == "-0" ? "0" : s
}
var d = ""
outline.applyWithBlock { el in
    let e = el.pointee
    let p = e.points
    switch e.type {
    case .moveToPoint: d += "M\(f(X(p[0].x))),\(f(Y(p[0].y)))"
    case .addLineToPoint: d += "L\(f(X(p[0].x))),\(f(Y(p[0].y)))"
    case .addQuadCurveToPoint: d += "Q\(f(X(p[0].x))),\(f(Y(p[0].y))) \(f(X(p[1].x))),\(f(Y(p[1].y)))"
    case .addCurveToPoint: d += "C\(f(X(p[0].x))),\(f(Y(p[0].y))) \(f(X(p[1].x))),\(f(Y(p[1].y))) \(f(X(p[2].x))),\(f(Y(p[2].y)))"
    case .closeSubpath: d += "Z"
    @unknown default: break
    }
}
let vw = ink.width + 2 * pad, vh = ink.height + 2 * pad
let dpPerUnit = capDp / Double(CTFontGetCapHeight(font))
let wDp = Double(vw) * dpPerUnit, hDp = Double(vh) * dpPerUnit
let xml = """
<?xml version="1.0" encoding="utf-8"?>
<!-- ZENLYGRAM: "\(text)" wordmark in place of Telegram's. Glyph outlines of \(CTFontCopyFullName(font) as String) (bundled in
     assets/fonts); generated by Tools/zenlygram/icons/zg_wordmark.swift. White fill, tinted by the callers. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="\(String(format: "%.3f", wDp))dp"
    android:height="\(String(format: "%.3f", hDp))dp"
    android:viewportWidth="\(f(vw))"
    android:viewportHeight="\(f(vh))">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="\(d)" />
</vector>

"""
try! xml.write(toFile: args[3], atomically: true, encoding: .utf8)
print("wrote \(args[3]): \(String(format: "%.2f x %.2f dp", wDp, hDp)), viewport \(f(vw)) x \(f(vh)), baseline at \(f(top)) units from top")
